import { randomBytes } from "node:crypto";
import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { createInterface } from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";
import { renderWranglerConfig } from "./wrangler-config.mjs";

const dryRun = process.argv.includes("--dry-run");
const root = process.cwd();
const rl = createInterface({ input, output });
function flag(name) {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? (process.argv[i + 1] ?? "") : undefined;
}
function ask(question, fallback = "") {
  return rl.question(fallback ? `${question} [${fallback}]: ` : `${question}: `).then((v) => v.trim() || fallback);
}
function normalizeDomain(value) {
  const raw = value.replace(/^https?:\/\//i, "").replace(/\/.*$/, "").trim();
  if (!/^[a-z0-9.-]+\.[a-z]{2,}$/i.test(raw)) throw new Error(`域名格式不正确：${value}`);
  return raw;
}
function secret() {
  return randomBytes(48).toString("base64url");
}
const current = JSON.parse(readFileSync(`${root}/wrangler.jsonc`, "utf8"));
const workerDefault = current.name ?? "pineboard";
const d1Default = current.d1_databases?.[0]?.database_name ?? "pineboard";
const r2Default = current.r2_buckets?.[0]?.bucket_name ?? "pineboard-assets";

console.log("Pineboard 初始化向导");
console.log("只生成本地 wrangler.site.jsonc 和 .dev.vars，不修改任何 tracked 文件。\n");
try {
  const worker = flag("worker") ?? await ask("Worker 名称", workerDefault);
  const domain = normalizeDomain(flag("domain") ?? await ask("站点域名（不带 https://）", "forum.example.com"));
  const siteUrl = `https://${domain}`;
  const cdnInput = flag("cdn") ?? await ask("CDN 域名（可留空；不建议默认开启）", "");
  const cdnUrl = cdnInput.trim() ? `https://${normalizeDomain(cdnInput)}` : "";
  const d1Name = flag("d1-name") ?? await ask("D1 database 名称", d1Default);
  const d1Id = flag("database-id") ?? await ask("D1 database_id");
  const r2Name = flag("r2-name") ?? await ask("R2 bucket 名称", r2Default);
  const adminEmail = flag("admin-email") ?? await ask("首个管理员邮箱（可留空）", "");
  if (!dryRun) {
    renderWranglerConfig({
      WORKER_NAME: worker,
      DOMAIN: domain,
      SITE_URL: siteUrl,
      D1_DATABASE_NAME: d1Name,
      D1_DATABASE_ID: d1Id,
      R2_BUCKET_NAME: r2Name,
      CDN_URL: cdnUrl,
    });
    const devVars = `# Generated by pnpm setup. Never commit.
BETTER_AUTH_SECRET=${secret()}
PASSWORD_PEPPER=${secret()}
IP_HASH_SALT=${secret()}
SITE_URL=http://localhost:5173
CDN_URL=
R2_BUCKET_NAME=${r2Name}
ENVIRONMENT=development
RESEND_API_KEY=
RESEND_WEBHOOK_SECRET=
TURNSTILE_SECRET=1x0000000000000000000000000000000AA
TURNSTILE_SITE_KEY=1x00000000000000000000AA
R2_ACCOUNT_ID=
R2_ACCESS_KEY_ID=
R2_SECRET_ACCESS_KEY=
ADMIN_EMAILS=${adminEmail}
EMAIL_TRANSPORT=log
DEV_RESET_TOKEN=${secret().slice(0, 32)}
`;
    if (existsSync(`${root}/.dev.vars`)) {
      const overwrite = await ask(".dev.vars 已存在，覆盖吗？(y/N)", "N");
      if (overwrite.toLowerCase() === "y") {
        writeFileSync(`${root}/.dev.vars`, devVars);
        chmodSync(`${root}/.dev.vars`, 0o600);
      }
    } else {
      writeFileSync(`${root}/.dev.vars`, devVars);
      chmodSync(`${root}/.dev.vars`, 0o600);
    }
  }
  console.log(`\n${dryRun ? "预演完成（未写入）" : "已生成 wrangler.site.jsonc 和 .dev.vars"}`);
  console.log(`Worker: ${worker}\nSite:   ${siteUrl}\nD1:     ${d1Name} (${d1Id})\nR2:     ${r2Name}\nCDN:    ${cdnUrl || "未配置（/files）"}`);
  console.log("\n接下来：");
  console.log("  1. pnpm install");
  console.log("  2. pnpm exec wrangler secret put BETTER_AUTH_SECRET");
  console.log("     pnpm exec wrangler secret put PASSWORD_PEPPER");
  console.log("     pnpm exec wrangler secret put IP_HASH_SALT");
  console.log("  3. pnpm db:migrate && pnpm dev");
  console.log("  4. 生产：设置 GitHub Variables/Secrets，打 v* tag 部署");
} catch (error) {
  console.error(`\n初始化中止：${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
} finally {
  rl.close();
}
